const assert = require('node:assert/strict');
const { chromium } = require('playwright');
const fs = require('node:fs');
const path = require('node:path');
(async () => {
	const browser = await chromium.launch({ executablePath: process.env.HOME + '/.cache/ms-playwright/chromium-1248/chrome-linux64/chrome' });
	try {
		const page = await browser.newPage({ viewport: { width: 402, height: 874 }, deviceScaleFactor: 2, colorScheme: 'dark' });
		const errors = []; page.on('pageerror', (e) => errors.push(e.message));
		const base = process.env.PREVIEW_URL ?? 'http://localhost:8084';
		const out = path.resolve(__dirname, '../.preview'); fs.mkdirSync(out, { recursive: true });
		await page.goto(base + '/pair');
		await page.getByText('Try a sample lesson', { exact: true }).waitFor();
		await page.evaluate(() => document.fonts.ready); await page.waitForTimeout(500);
		await page.screenshot({ path: path.join(out, '06-pair-v2.png') });
		const pairTitle = await page.getByText('Pair with your computer', { exact: true }).boundingBox();
		const saved = JSON.stringify({ url: 'https://saved.invalid', token: 'saved-test-credential', name: 'Saved computer' });
		await page.evaluate((value) => localStorage.setItem('learnharness-phone-preview', value), saved);
		let requests = 0;
		await page.route('**/api/**', (route) => { requests++; return route.abort(); });
		const started = performance.now();
		await page.getByText('Try a sample lesson', { exact: true }).click();
		await page.getByText('SAMPLE', { exact: true }).waitFor(); await page.getByText('The chain rule', { exact: true }).waitFor();
		await page.waitForTimeout(500);
		await page.screenshot({ path: path.join(out, '01-home-sample.png') });
		const homeMs = performance.now() - started;
		assert.equal(await page.evaluate(() => localStorage.getItem('learnharness-phone-preview')), saved);
		await page.getByText('The chain rule', { exact: true }).click();
		await page.getByText('ANSWER', { exact: true }).click();
		const answerAt = performance.now();
		await page.getByRole('radio').first().click();
		await page.getByPlaceholder('What makes you think so?').fill('Multiply the local stretch factor by the nudge.');
		await page.getByText('SUBMIT', { exact: true }).click();
		await page.getByText(/^Let \$h\(x\)/).waitFor();
		const answerMs = performance.now() - answerAt;
		await page.getByLabel('Back', { exact: true }).click();
		await page.getByText("PRACTICE WHAT'S DUE", { exact: true }).click();
		await page.getByPlaceholder('Work through the problem here').waitFor({ timeout: 8000 }).catch(async (error) => { await page.screenshot({ path: path.join(out, 'sample-error.png') }); console.error(await page.locator('body').innerText(), errors); throw error; });
		await page.getByPlaceholder('Work through the problem here').fill('Outside in: cube, then cos, then 5x.');
		await page.getByText('SUBMIT WORK', { exact: true }).click();
		await page.getByText('NEXT PROBLEM', { exact: true }).waitFor();
		const practiceMs = performance.now() - started - homeMs;
		await page.getByLabel('Back', { exact: true }).click();
		await page.getByText('SAMPLE', { exact: true }).click();
		assert.equal(requests, 0);
		const demoRequests = requests;
		await page.getByText('PAIR WITH YOUR COMPUTER', { exact: true }).click();
		await page.getByText('Try a sample lesson', { exact: true }).waitFor();
		assert.equal(await page.evaluate(() => localStorage.getItem('learnharness-phone-preview')), saved);
		assert.deepEqual(errors, []);
		const receipt = { viewport: { width: 402, height: 874, scale: 2 }, pairTitle, homeMs, answerMs, practiceMs, apiRequests: demoRequests, errors, credentials: 'untouched', apiBlocked: true };
		fs.writeFileSync(path.join(out, 'public-browser.json'), JSON.stringify(receipt, null, 2)); console.log(JSON.stringify(receipt, null, 2));
	} finally { await browser.close(); }
})().catch((error) => { console.error(error); process.exit(1); });
