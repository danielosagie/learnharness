// NODE_PATH=/path/to/playwright/node_modules node scripts/preview.cjs
const { chromium } = require('playwright');
const fs = require('node:fs');
const path = require('node:path');
(async () => {
	const out = path.resolve(__dirname, '../.preview'); fs.mkdirSync(out, { recursive: true });
	const browser = await chromium.launch({ executablePath: process.env.HOME + '/.cache/ms-playwright/chromium-1248/chrome-linux64/chrome' });
	const page = await browser.newPage({ viewport: { width: 402, height: 874 }, deviceScaleFactor: 2, colorScheme: 'dark' });
	const errors = []; page.on('pageerror', (e) => errors.push(e.message));
	const base = process.env.PREVIEW_URL ?? 'http://localhost:8084';
	await page.goto(base + '/pair', { waitUntil: 'load' });
	await page.getByText('ENTER CODE INSTEAD', { exact: true }).waitFor();
	await page.waitForTimeout(1000);
	await page.screenshot({ path: path.join(out, '06-pair.png') });
	await page.getByText('ENTER CODE INSTEAD', { exact: true }).click();
	await page.getByPlaceholder('100.x.y.z or computer.tailnet').fill('127.0.0.1');
	await page.getByPlaceholder('CODE1234').fill('ABCD1234');
	await page.getByText('PAIR PHONE', { exact: true }).click();
	await page.getByText('DUE FOR REVIEW', { exact: true }).waitFor();
	await page.getByText('The chain rule', { exact: true }).waitFor();
	await page.waitForTimeout(1000);
	await page.screenshot({ path: path.join(out, '01-home.png') });
	await page.getByText('The chain rule', { exact: true }).click();
	await page.getByText('ANSWER', { exact: true }).waitFor();
	await page.waitForTimeout(1000);
	await page.screenshot({ path: path.join(out, '02-session.png') });
	await page.getByText('ANSWER', { exact: true }).click();
	await page.getByText('−0.02', { exact: true }).click();
	await page.getByLabel('Confidence').click({ position: { x: 253, y: 11 } });
	await page.getByPlaceholder('What makes you think so?').fill('−4 times ½ is −2, so 0.01 becomes −0.02');
	await page.getByPlaceholder('What makes you think so?').blur();
	await page.waitForTimeout(1000);
	await page.screenshot({ path: path.join(out, '03-check.png') });
	await page.goto(base + '/session/preview-practice', { waitUntil: 'load' });
	await page.getByPlaceholder('Work through the problem here').fill('Outside in: cube, then cos, then 5x.\n\n$3\\cos^2(5x)\\cdot(-\\sin 5x)\\cdot5$\n\n$=-15\\cos^2(5x)\\sin(5x)$');
	await page.getByPlaceholder('Work through the problem here').blur();
	await page.getByLabel('Edit your work').waitFor();
	await page.waitForTimeout(1000);
	await page.screenshot({ path: path.join(out, '04-practice.png') });
	await page.goto(base + '/session/preview-result', { waitUntil: 'load' });
	await page.getByText('back in 21 days', { exact: true }).waitFor();
	await page.waitForTimeout(1000);
	await page.screenshot({ path: path.join(out, '05-result.png') });
	const fonts = await page.evaluate(async () => { await document.fonts.load('17px SourceSans3Bold'); await document.fonts.ready; return [...document.fonts].map((f) => ({ family: f.family, status: f.status })); });
	fs.writeFileSync(path.join(out, 'browser.json'), JSON.stringify({ viewport: { width: 402, height: 874, scale: 2 }, fonts, errors }, null, 2));
	console.log(JSON.stringify({ screenshots: 6, fonts, errors }, null, 2));
	await browser.close();
})().catch((e) => { console.error(e); process.exit(1); });
